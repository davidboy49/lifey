"""The vidhealth follower, against a stand-in 'old' database in the same server."""
import json
import os

import psycopg
import pytest

from app.health import follow_vidhealth as follow

OLD_SCHEMA = """
DROP TABLE IF EXISTS source_payloads, daily_metrics;
CREATE TABLE source_payloads (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date TEXT NOT NULL,
  endpoint TEXT NOT NULL, payload_hash TEXT NOT NULL, received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  payload JSONB NOT NULL);
CREATE TABLE daily_metrics (date TEXT PRIMARY KEY, raw_json TEXT, synced_at TIMESTAMPTZ);
"""


@pytest.fixture
def old(pg, database_url, monkeypatch):
    with psycopg.connect(database_url, autocommit=True) as c:
        c.execute(OLD_SCHEMA)
    monkeypatch.setenv("OLD_DATABASE_URL", database_url)
    yield
    with psycopg.connect(database_url, autocommit=True) as c:
        c.execute("DROP TABLE IF EXISTS source_payloads, daily_metrics")


def add_payload(url, day, received, payload):
    with psycopg.connect(url) as c:
        c.execute("INSERT INTO source_payloads (date, endpoint, payload_hash, received_at, payload) "
                  "VALUES (%s,'fetch_attempt','h',%s,%s::jsonb)", (day, received, json.dumps(payload)))


def recent(days_ago=0):
    from datetime import timedelta
    from app.health import quality
    return (quality.today() - timedelta(days=days_ago)).isoformat()


def test_follower_brings_new_payloads_across_and_is_repeatable(old, pg, database_url):
    day = recent(1)
    add_payload(database_url, day, "2026-10-09 08:00:00+00", {"summary": {"totalSteps": 100}})
    assert follow.main(["--days", "7"]) == 0
    assert pg.execute("SELECT steps FROM health.daily_metrics WHERE date=%s", (day,)).fetchone()[0] == 100

    add_payload(database_url, day, "2026-10-09 20:00:00+00", {"summary": {"totalSteps": 250}})
    follow.main(["--days", "7"])
    follow.main(["--days", "7"])  # again: no change
    pg.rollback()
    assert pg.execute("SELECT steps FROM health.daily_metrics WHERE date=%s", (day,)).fetchone()[0] == 250
    assert pg.execute("SELECT count(*) FROM health.source_payloads WHERE date=%s", (day,)).fetchone()[0] == 2


def test_follower_cannot_write_to_the_old_database(old, database_url):
    with psycopg.connect(database_url) as conn:
        conn.read_only = True
        with pytest.raises(psycopg.errors.ReadOnlySqlTransaction):
            conn.execute("INSERT INTO daily_metrics (date) VALUES ('2026-01-01')")


def test_days_only_in_stored_json_are_followed_too(old, pg, database_url):
    day = recent(2)
    with psycopg.connect(database_url) as c:
        c.execute("INSERT INTO daily_metrics (date, raw_json, synced_at) VALUES (%s,%s,%s)",
                  (day, json.dumps({"summary": {"totalSteps": 7}}), "2026-10-08 09:30:00+00"))
    assert follow.main(["--days", "7"]) == 0
    row = pg.execute("SELECT steps, synced_at FROM health.daily_metrics WHERE date=%s", (day,)).fetchone()
    assert row[0] == 7 and row[1].isoformat().startswith("2026-10-08T09:30")


def test_requires_the_old_database_url(pg, monkeypatch):
    monkeypatch.delenv("OLD_DATABASE_URL", raising=False)
    with pytest.raises(SystemExit):
        follow.main([])
