SQL = """
-- Files attached to a journal entry. The bytes live on disk (ATTACHMENTS_DIR);
-- this row is the index. Deleting the entry removes these rows, and the code
-- removes the files.
CREATE TABLE journal.attachments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id       BIGINT NOT NULL REFERENCES journal.activity_logs(id) ON DELETE CASCADE,
    filename     TEXT NOT NULL,
    mime         TEXT NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
    bytes        INTEGER NOT NULL CHECK (bytes > 0),
    width        INTEGER,
    height       INTEGER,
    sha256       TEXT NOT NULL,
    stored_name  TEXT NOT NULL UNIQUE,
    thumb_name   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX attachments_log_idx ON journal.attachments (log_id);

-- One row per nightly backup attempt, written by deploy/backup.sh.
CREATE TABLE journal.backup_runs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at  TIMESTAMPTZ,
    ok           BOOLEAN,
    bytes        BIGINT,
    files        INTEGER,
    destination  TEXT,
    detail       TEXT
);
"""


def upgrade() -> None:
    op.execute(SQL)
