SQL = """
-- One row per event or day looked back on. The event name and date are typed by the owner, never picked
-- from data. Mood and energy are optional (NULL = not answered). Loop tags are a fixed set so they can be
-- counted and filtered; an empty array means "none ticked".
CREATE TABLE journal.event_reviews (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date          DATE NOT NULL,
    event         TEXT NOT NULL CHECK (length(event) BETWEEN 1 AND 120),
    mood          SMALLINT CHECK (mood IS NULL OR mood BETWEEN 1 AND 5),
    energy        SMALLINT CHECK (energy IS NULL OR energy BETWEEN 1 AND 5),
    notes         TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 2000),
    went_well     TEXT NOT NULL DEFAULT '' CHECK (length(went_well) <= 2000),
    would_change  TEXT NOT NULL DEFAULT '' CHECK (length(would_change) <= 2000),
    loop_tags     TEXT[] NOT NULL DEFAULT '{}'
                  CHECK (loop_tags <@ ARRAY['loneliness','urge','drinking','stress','pois','poor_sleep']::TEXT[]),
    lesson        TEXT NOT NULL DEFAULT '' CHECK (length(lesson) <= 200),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX event_reviews_date_idx ON journal.event_reviews (date DESC, id DESC);
CREATE INDEX event_reviews_tags_idx ON journal.event_reviews USING GIN (loop_tags);

-- Photos on a review. Same storage as journal.attachments (bytes in ATTACHMENTS_DIR, this row is the
-- index); a separate table because those rows must belong to a journal entry.
CREATE TABLE journal.event_review_photos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id    BIGINT NOT NULL REFERENCES journal.event_reviews(id) ON DELETE CASCADE,
    filename     TEXT NOT NULL,
    mime         TEXT NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp')),
    bytes        INTEGER NOT NULL CHECK (bytes > 0),
    width        INTEGER,
    height       INTEGER,
    sha256       TEXT NOT NULL,
    stored_name  TEXT NOT NULL UNIQUE,
    thumb_name   TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX event_review_photos_review_idx ON journal.event_review_photos (review_id);

-- The connector may now create an event review (owner's decision 2026-11-09); its audit row points at it.
ALTER TABLE journal.connector_audit DROP CONSTRAINT connector_audit_ref_kind_check;
ALTER TABLE journal.connector_audit ADD CONSTRAINT connector_audit_ref_kind_check
    CHECK (ref_kind IN ('activity_log', 'proposal', 'event_review'));
"""


